def _item(tipo, nome, sistema='', papel='', manipulado=False):
    return {
        'tipo': tipo,
        'nome': nome,
        'sistema': sistema,
        'papel': papel,
        'manipulado': manipulado,
    }


def itens_uma_seed():
    itens = [_item('prato', nome) for nome in PRATOS_EXTRA_SEED]
    itens += [_item('suplemento', nome) for nome in SUPLEMENTOS_SEED]
    itens += [
        _item('suplemento', nome, manipulado=True)
        for nome in SUPLEMENTOS_MANIPULADOS_SEED
    ]
    itens += [
        _item('enteral', nome, sistema='aberto', papel='dieta')
        for nome in ENTERAL_ABERTO_SEED
    ]
    itens += [
        _item('enteral', nome, sistema='fechado', papel='dieta')
        for nome in ENTERAL_FECHADO_SEED
    ]
    itens += [_item('formula', nome) for nome in FORMULAS_INFANTIS_SEED]
    itens += [_item('modulo', nome) for nome in MODULOS_SEED]
    return itens
